"""Scoreboard of the build-program ladder from bench/ledger (RFC-0018 A2, RFC-0027 §3).

  python3 bench/scoreboard.py            # print the table
  python3 bench/scoreboard.py --write    # rewrite bench/scoreboard.md
  python3 bench/scoreboard.py --check    # fail if bench/scoreboard.md is stale

Bootstrap generator: task E17-02 moves it into `stele-bench scoreboard` with the same
output. It reads inference records only and never edits a ledger.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'bench/scoreboard.md'
# Records made before task E17-01 carry no model_config.rung.
RUNGS = {'dev/synthetic-8layer-t64': 'L1', 'dev/stories42m-t64': 'L2a', 'dev/stories110m-t64': 'L2c'}
ORDER = ['L0', 'L1', 'L2a', 'L2b', 'L2c', 'L3a', 'L3b', 'L3c', 'L4', 'L5', 'L6']


def rows():
    out = []
    for path in sorted((ROOT / 'bench/ledger').glob('*.json')):
        r = json.loads(path.read_text())
        if r['kind'] != 'inference':
            continue
        rung = r['model_config'].get('rung') or RUNGS.get(r['workload']) or r['workload']
        tokens = (r['prompt_tokens'] + r['generated_tokens']) * r['batch_size']
        k = r['kernel_counters']
        cells = k.get('committed_cells', k.get('stacked_source_cells_padded'))
        lookups = k.get('lookup_positions', k.get('lookup_ledger_numerator_sum'))
        prove = r['prover_time_ns'] / 1e9
        out.append((ORDER.index(rung) if rung in ORDER else len(ORDER), rung, path.name, [
            rung, r['profile'] + {1: ' (dev-zk)', 4: ' (dev-zk, A8 sources)'}.get(
                r['model_config'].get('profile_byte'), '')
            # E12-32: a privacy-test record's time is the whole test (two proofs and their checks).
            + (' privacy test, whole-test time' if 'privacy' in r['workload'] else ''),
            r['device'], str(r['model_config'].get('threads', '—')),
            f'{prove:.2f}', '—' if 'privacy' in r['workload'] else f'{tokens / prove:.3f}', f"{r['verifier_time_ns']['rust'] / 1e9:.2f}",
            f"{r['proof_size_bytes'] / 1e6:.1f}", f"{k['prove_peak_rss_bytes'] / 1e9:.1f}"
            if 'prove_peak_rss_bytes' in k else '—',
            f'{cells // tokens:,}' if cells else '—', f'{lookups // tokens:,}' if lookups else '—',
            str(k.get('weight_reads', '—')), 'none' if r['profile'] == 'development' else '?',
            f"{r['controls']['passed']}/{r['controls']['total']}",
            f"[{path.stem}](ledger/{path.name}) @ `{r['commit'][:7]}`"]))
    return [cols for _, _, _, cols in sorted(out, key=lambda x: x[:3])]


def render():
    head = ['Rung', 'Profile', 'Device', 'Threads', 'Prove s', 'Tok/s', 'Verify s', 'Proof MB', 'RSS GB',
            'Cells/token', 'Lookups/token', 'Weight reads', 'λ bits', 'Controls', 'Ledger']
    table = rows()
    seen = {cols[0] for cols in table}
    lines = ['# Scoreboard', '',
             'Generated by `python3 bench/scoreboard.py --write` from `bench/ledger/`. Do not edit.',
             'Rungs and columns: RFC-0027 §3, RFC-0018 A2. One row per inference record.', '',
             '| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    lines += ['| ' + ' | '.join(cols) + ' |' for cols in table]
    lines += ['', 'Rungs with no record: ' + ', '.join(r for r in ORDER if r not in seen) + '.', '',
              '- Cells/token and Lookups/token before task E17-01 are upper bounds read from the proof: the padded',
              '  stacked-source size and the sum of the verifier\'s LU numerators (tables included). A dash',
              '  means the record does not carry the counter.',
              '- λ is `none` for every development-profile record (RFC-0026 §1.2).',
              '- Rows on different devices or thread counts are not a comparison (Workflow 04).', '']
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write', action='store_true')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    text = render()
    if a.write:
        OUT.write_text(text)
    elif a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print('bench/scoreboard.md is stale; run python3 bench/scoreboard.py --write', file=sys.stderr)
            return 1
    else:
        print(text, end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
