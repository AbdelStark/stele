def timing(v, names):
    keys(v['stages_ns'], names)
    assert all(type(t) is int and t > 0 for t in v['stages_ns'].values())
    assert v['remainder_ns'] == v['total_ns']-sum(v['stages_ns'].values()) >= 0


def delta(after, before):
    PCS.hashes(after); PCS.hashes(before)
    result = {k:after[k]-before[k] for k in PCS.HASH_KEYS}
    assert min(result.values()) >= 0
    return result


def packet_size(d, ell, m, blowup, certificate=False):
    q = PCS.policy(m, blowup)[0 if certificate else 1]
    return 1+4*d*(1 << m)+q*(4*(1 << ell)+32*(m+blowup))


def sections(q, rows, quotient_bytes):
    d, n, r, b = q['degree'], q['n'], q['repetitions'], q['advice_blowup']
    input_blowup = q['input']['blowup']
    m, a = (n-1).bit_length(), rows.bit_length()-1
    width = 4*d
    tree = lambda k: width*(2+2*k*k+3*k)
    mu_m = 8+(d.bit_length()-1)
    lookup = lambda ell, rate: 2+r*(32+packet_size(d,0,mu_m,1,True)+tree(ell+m)+tree(8)
        +width*(4*(ell+m)+3)+packet_size(d,ell,m,rate)+width+packet_size(d,0,mu_m,1))
    return [('header',34), ('advice_certificate',packet_size(d,a,m,b,True)),
        ('input_lookup',lookup(2,input_blowup)), ('advice_lookup',lookup(a,b)),
        ('aggregate',width*(4*m+5+rows)), ('input_group',packet_size(d,2,m,input_blowup)),
        ('advice_group',packet_size(d,a,m,b)), ('output',width*(4*m+2+quotient_bytes)),
        ('output_group',packet_size(d,a,m,b))]


