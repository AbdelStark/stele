def artifact(raw):
    return dict(bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest())


def compact(n, py, raw):
    q=n['request'];wire=bytes.fromhex(q['proof_hex']);record=n['verification']['record']
    offset=0;pieces=[]
    for name,size in sections(q,len(record['groups'][1]['claims']),len(record['groups'][2]['claims'])-1):
        pieces.append(dict(name=name,**artifact(wire[offset:offset+size])));offset+=size
    record_digest=artifact(json.dumps(record,sort_keys=True,separators=(',',':')).encode())
    verification={k:v for k,v in n['verification'].items() if k!='record'}|{'record':record_digest}
    return {k:v for k,v in n.items() if k not in ('request','verification')}|dict(verification=verification,
        public={k:v for k,v in q.items() if k not in ('input','proof_hex','following_hex')},request=artifact(raw),proof=artifact(wire),sections=pieces,
        input_certificate=artifact(bytes.fromhex(q['input']['certificate_hex'])),following=artifact(bytes.fromhex(q['following_hex'])),
        python={k:v for k,v in py.items() if k!='verification'}|{'verification':verification})


def check_cases(records):
    assert [(r['scenario'],r['field_degree'],r['sample']) for r in records]==CASES


def identity(v):
    volatile={'stages_ns','total_ns','remainder_ns','sample','processes','artifacts'}
    if isinstance(v,dict): return {k:identity(x) for k,x in v.items() if k not in volatile}
    if isinstance(v,list): return [identity(x) for x in v]
    return v


def assemble(metadata, records):
    stages={f'{i}/{lang}/{stage}':t for i,r in enumerate(records) for lang,v in [('native',r),('python',r['python'])] for stage,t in (v['stages_ns']|{'remainder':v['remainder_ns']}).items()}
    return dict(schema_version=1,kind='micro',workload='micro/requant',commit=metadata['commit'],toolchain=metadata['toolchain'],device=metadata['device'],driver='not-applicable',
        model_config=dict(**metadata,samples=records),plan_digest=hashlib.sha256(json.dumps(metadata['plan'],sort_keys=True,separators=(',',':')).encode()).hexdigest(),
        profile='standard',bindings_all_on=True,batch_size=1,prompt_tokens=0,generated_tokens=0,prover_time_ns=sum(stages.values()),witness_recompute_ns=0,stage_times_ns=stages,
        kernel_counters=dict(native_producer_local_hashes=sum(r['producer_usage']['non_transcript']['hash_evaluations'] for r in records)),
        proof_size_bytes=0,verifier_time_ns=dict(rust=0,python=0),controls=dict(total=0,passed=0,failed=0),
        note='Complete bounded native Requant witness/registration/production and native plus independent Python closed consumers, all bindings enabled. Component proof bytes, actual disjoint timings and complete process RSS in samples. Prove includes internal multiplicity registration; separate external imports are additional actual calls. Capacity observations are partial, never a combined heap peak. Root inference fields remain zero; standard is a schema tag, not profile/privacy/inference admission or a performance comparison.')


def main():
    if sys.version_info[:2]!=(3,12) or sys.flags.optimize:
        raise SystemExit('requires Python 3.12 with assertions enabled')
    if len(sys.argv)!=2 or (platform.system(),platform.machine())!=('Darwin','arm64'):
        raise SystemExit('usage: uv run --no-project --python 3.12 python bench/requant.py <new-external-ledger.json>')
    output=Path(sys.argv[1]).absolute();raw=output.with_suffix('.samples')
    if output.exists() or raw.exists() or ROOT in output.resolve().parents or run('git','status','--porcelain'):
        raise SystemExit('requires clean committed source and new external output/sample paths')
    commit,tree=run('git','rev-parse','HEAD'),run('git','rev-parse','HEAD^{tree}')
    plan=dict(cases=CASES,scenarios=SCENARIOS,workers=1,positions=4096,public_bytes=32_000_000,proof_bytes=32_000_000,
        sampling='three samples per cell in fixed order; fresh native and locked Python workers; no warmup, retry or discarded samples; shared host and original workers preserved',
        inputs='scalar [-128]; ties [-1,0,1]; wide [MIN,0,MAX]; shift62 [MIN,MAX]; radix255 [-128,0,127]; radix256 [-32768,0,32767]; output point consecutive base-field values from2; fixed public prefix',
        timing='actual disjoint stages and remainder; native prove includes internal mu setup/registration; external imports separate; startup and serialization in process wall/RSS only',
        capacities=MEMORY_SCOPE,usage='full original setup, producer registrations, separate native/Python imports, closed snapshots and diagnostic deltas; no cumulative snapshot addition',
        scope='bounded operation only; no full inference, source-plan authority, configured profile, privacy, W8 or scale/comparative claim')
    raw.mkdir(parents=True)
    def save(path,data):
        with path.open('xb') as f:f.write(data)
    sources={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in run('git','ls-files').splitlines()
             if p.startswith(('crates/','research/','tests/negative-controls/','bench/','scripts/')) and (ROOT/p).is_file()}
    metadata=dict(commit=commit,tree=tree,plan=plan,source_sha256=sources,toolchain=run('rustc','-Vv'),cargo=run('cargo','--version'),
        artifact_directory=str(raw.resolve()),os=platform.platform(),python=sys.version,uv=run('uv','--version'),device=platform.machine()+' '+run('sysctl','-n','machdep.cpu.brand_string'))
    save(raw/'provenance-before-build.json',(json.dumps(metadata,indent=2)+'\n').encode())
    build_command=['cargo','build','-p','stele-negative-controls','--example','requant_bench','--release','--locked','--offline','--message-format=json-render-diagnostics']
    build=subprocess.run(build_command,cwd=ROOT,capture_output=True)
    save(raw/'build.jsonl',build.stdout);save(raw/'build.stderr',build.stderr);save(raw/'build.exit',f'{build.returncode}\n'.encode())
    build.check_returncode()
    artifacts=[decode(line) for line in build.stdout.splitlines()]
    executables={a['executable'] for a in artifacts if a.get('reason')=='compiler-artifact'
        and a['target']['name']=='requant_bench' and a['target']['kind']==['example'] and a['executable']}
    assert len(executables)==1
    binary=Path(executables.pop()).resolve();assert binary.is_file()
    metadata.update(binary=str(binary),binary_sha256=hashlib.sha256(binary.read_bytes()).hexdigest(),build_command=build_command)
    save(raw/'provenance.json',(json.dumps(metadata,indent=2)+'\n').encode())
    def unchanged():
        assert run('git','rev-parse','HEAD')==commit and run('git','rev-parse','HEAD^{tree}')==tree
        assert not run('git','status','--porcelain') and hashlib.sha256(binary.read_bytes()).hexdigest()==metadata['binary_sha256']
    records=[]
    for i,(scenario,d,sample) in enumerate(CASES):
        unchanged();paths={};processes={}
        def worker(name,command):
            stats=raw/f'{i:02d}.{name}.time';start=perf_counter_ns()
            result=subprocess.run(['/usr/bin/time','-l','-o',str(stats),*command],cwd=ROOT,capture_output=True)
            wall=perf_counter_ns()-start
            for suffix,value in [('stdout',result.stdout),('stderr',result.stderr),('exit',f'{result.returncode}\n'.encode())]:
                path=raw/f'{i:02d}.{name}.{suffix}';save(path,value);paths[path.name]=artifact(value)
            report=stats.read_bytes();paths[stats.name]=artifact(report);result.check_returncode()
            peaks=[int(line.split()[0]) for line in report.decode().splitlines() if 'maximum resident set size' in line]
            assert len(peaks)==1 and peaks[0]>0 and wall>0
            processes[name]=dict(wall_ns=wall,peak_rss_bytes=peaks[0])
            return decode(result.stdout)
        n=worker('native',[str(binary),scenario,str(d)])
        request=(json.dumps(n['request'],sort_keys=True,separators=(',',':'))+'\n').encode()
        path=raw/f'{i:02d}.request.json';save(path,request);paths[path.name]=artifact(request)
        py=worker('python',python_command(path));receipt(n,py,request,scenario,d);unchanged()
        records.append(compact(n,py,request)|dict(sample=sample,processes=processes,artifacts=paths))
        print(f'Validated {scenario}/{d}/{sample}',flush=True)
    check_cases(records);unchanged()
    for i in range(0,len(records),3):assert identity(records[i])==identity(records[i+1])==identity(records[i+2])
    encoded=(json.dumps(assemble(metadata,records),separators=(',',':'))+'\n').encode()
