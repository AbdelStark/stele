    assert q['point'] == [[2+j]+[0]*(d-1) for j in range(m)]
    assert len(q['value']) == d and all(x < 2147483647 for x in q['value'])
    assert py['request_sha256'] == hashlib.sha256(raw).hexdigest()
    assert set(py['sources']) == PYTHON_SOURCES
    assert all(hashlib.sha256((ROOT/p).read_bytes()).hexdigest() == h for p,h in py['sources'].items())
    keys(py['runtime'], 'version executable implementation optimization')
    assert py['runtime']['version'].startswith('3.12.') and py['runtime']['implementation']=='cpython'
    assert Path(py['runtime']['executable']).is_absolute()
    assert py['runtime']['optimization']==0
    assert py['verification'] == n['verification']
    v = n['verification']; keys(v,'imports usage record continuation')
