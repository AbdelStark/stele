    source = PCS.hex_bytes(q['input']['source_hex'],105)
    assert source[73:].hex()==q['input']['root_hex']
    PCS.hex_bytes(q['input']['certificate_hex'],packet_size(d,2,m,input_blowup,True))
    assert len(n['originals'])==2
    for i,(ell,rate,ident) in enumerate([(2,input_blowup,73),(rows.bit_length()-1,blowup,base+2)]):
        original=n['originals'][i]
