struct Case {
    model: Model,
    prep: Preparation<'static>,
    scales: Scales,
    bytes: [&'static [u8]; 3],
    artifact: Vec<u8>,
}

fn load(name: &str) -> Case {
    let all: serde_json::Value = serde_json::from_str(JSON).expect("json");
    // The manifest pins the fixture bytes (regenerated by `synthetic_e2e.py`).
    assert_eq!(
        blake3::hash(RAW).to_hex().as_str(),
        all["blake3"].as_str().expect("blake3")
    );
    let c = all["cases"]
        .as_array()
        .expect("cases")
        .iter()
        .find(|c| c["name"] == name)
        .expect("case")
        .clone();
    let span = |key: &str| {
        let o = c[key]["offset"].as_u64().expect("offset") as usize;
        let n = c[key]["length"].as_u64().expect("length") as usize;
        &RAW[o..o + n]
    };
    let artifact = span("artifact").to_vec();
    // The fixture pins each artifact's BLAKE3 digest; the executor checks it on load.
    assert_eq!(
        blake3::hash(&artifact).to_hex().as_str(),
        c["artifact_id"].as_str().expect("artifact id")
    );
    let model = Model::decode(span("model")).expect("model");
    let prep = Preparation::decode(&model, span("preparation")).expect("prep");
    let scales = Scales::decode(&model, span("scales")).expect("scales");
    Case {
        model,
        prep,
        scales,
        bytes: [span("model"), span("scales"), span("preparation")],
        artifact,
    }
}

impl Case {
    fn executor<'a>(&'a self, artifact: &'a [u8]) -> Executor<'a> {
        let id = *blake3::hash(artifact).as_bytes();
        Executor::new(
            &self.model,
            &self.prep,
            &self.scales,
            artifact,
            &id,
            1 << 36,
        )
        .expect("load")
    }

    fn public(&self, committed: &Committed<'_>, weights: &Weights) -> Public {
        Public {
            model: self.bytes[0].to_vec(),
            scales: self.bytes[1].to_vec(),
            preparation: self.bytes[2].to_vec(),
            vectors: weights.vectors.clone(),
            commitment: committed.commitment.clone(),
            sources: weights.sources(),
        }
    }
}

/// Greedy continuation of token 1 to `t` tokens, checked over `[0, t)` with `y`.
fn greedy(executor: &mut Executor<'_>, t: usize) -> Statement {
    let mut tokens = vec![1u32];
    let mut cache = None;
    loop {
        let (step, next) = executor
            .step(*tokens.last().expect("token"), cache.as_ref())
            .expect("step");
        cache = Some(next);
        let logits = step.logits();
        let max = *logits.iter().max().expect("logits");
        let y = logits.iter().position(|v| *v == max).expect("argmax") as u32;
        if tokens.len() == t {
            return Statement {
                tokens,
                start: 0,
                end: t as u32,
                next: Some(y),
            };
        }
        tokens.push(y);
    }
}

/// FNV-1a of proof bytes: any byte change moves it (INV-8).
fn fnv(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325u64, |h, b| {
        (h ^ u64::from(*b)).wrapping_mul(0x0100_0000_01b3)
    })
}

fn run(name: &str, t: usize, sources: Sources) -> u64 {
    proved(name, t, sources).0
}

/// The proof's FNV and the verifier's ledger.
fn proved(name: &str, t: usize, sources: Sources) -> (u64, Ledger) {
    let case = load(name);
    let mut executor = case.executor(&case.artifact);
    let statement = greedy(&mut executor, t);
    let weights =
        Weights::from_artifact_sources(&case.model, &case.artifact, sources).expect("weights");
    let clock = Instant::now();
    let committed = Committed::new(&weights).expect("commitment");
    let commit_ms = clock.elapsed().as_millis();
    let public = case.public(&committed, &weights);
    let clock = Instant::now();
    let proof = prove(&public, &mut executor, &weights, &committed, &statement).expect("prove");
    let prove_ms = clock.elapsed().as_millis();
    let sections = container::decode(&proof).expect("container");
    for (label, list) in [
        ("groups", &sections.groups),
        ("multiplicities", &sections.multiplicities),
        ("identities", &sections.identities),
        ("lookups", &sections.lookups),
        ("matmuls", &sections.matmuls),
        ("openings", &sections.openings),
    ] {
        let bytes: usize = list.iter().map(Vec::len).sum();
        eprintln!("{label}: {} sections, {bytes} bytes", list.len());
    }
    let clock = Instant::now();
    let ledger = verify(&public, &statement, &proof).expect("verify");
    let verify_ms = clock.elapsed().as_millis();
    eprintln!(
        "{name}: T={t} proof {} bytes (fnv {:016x}), commit {commit_ms} ms, prove {prove_ms} ms, verify {verify_ms} ms\n{ledger}",
        proof.len(),
        // Identity check across prover-side changes (INV-8): any byte change moves it.
        fnv(&proof)
    );
    (fnv(&proof), ledger)
}

/// E8-05c: the enumerated rounds carry every ledger numerator, each entry's largest
/// round, and a tensor round per certificate. Returns (rounds, worst round's line and
/// name, its bits, floor bits), bits in 1/1024.
fn enumerated(ledger: &Ledger) -> (usize, String, u64, u64) {
    let rounds = ledger.rounds();
    let field = |r: &stele_prover::development::Round| match r.error {
        RoundError::Field(n) => n,
        RoundError::Pow2(_) => 0,
    };
    let algebraic: u64 = rounds
        .iter()
        .filter(|r| !r.line.starts_with("PCS"))
        .map(field)
        .sum();
    assert_eq!(algebraic, ledger.interactive());
    // `rounds()` lists each entry's rounds in turn: per entry, ⌈n/r⌉ rounds whose
    // largest is min(r, n) and whose sum is n (#367 review: per entry, not per name).
    let mut algebraic_rounds = rounds.iter().filter(|r| !r.line.starts_with("PCS"));
    for e in &ledger.entries {
        let r = e.round.clamp(1, e.numerator.max(1));
        let count = e.numerator.div_ceil(r) as usize;
        let own: Vec<u64> = algebraic_rounds.by_ref().take(count).map(field).collect();
        assert_eq!(own.len(), count, "{e:?}");
        assert_eq!(own.iter().sum::<u64>(), e.numerator, "{e:?}");
        assert_eq!(
            own.iter().max().copied().unwrap_or(0),
            r.min(e.numerator),
            "{e:?}"
        );
    }
    assert!(algebraic_rounds.next().is_none());
    let tensors = rounds.iter().filter(|r| r.line == "PCS tensor").count();
    // The stack, each check's multiplicity source and at least one model source.
    let checks = ledger.entries.iter().filter(|e| e.line == Line::Lu).count();
    assert!(
        tensors > 1 + checks,
        "{tensors} tensor rounds, {checks} checks"
    );
    let (worst, bits) = ledger.worst().expect("rounds");
    (
        rounds.len(),
        format!("{} {}", worst.line, worst.name),
        bits,
        ledger.floor_bits(),
    )
}

#[test]
fn enumerates_every_round_of_the_one_layer_window() {
    for (sources, k_q) in [(Sources::Expander, 0), (Sources::CircleAll, 16)] {
        let (_, ledger) = proved("one-layer", 4, sources);
        let (rounds, worst, bits, floor) = enumerated(&ledger);
        eprintln!("{sources:?}: {rounds} rounds, worst {worst} {bits}/1024, floor {floor}/1024");
        // Policy 1 column rounds never grind; Policy 2 ones grind k_q = 16.
        assert!(ledger
            .rounds()
            .iter()
            .filter(|r| r.line == "PCS column")
            .all(|r| r.grind == k_q));
        assert!(floor < bits, "the floor is at least the worst round");
    }
}

/// The eight-layer acceptance window's worst round and floor (E8-05c); `verify-dev`
/// prints FAIL for both. Release build only.
#[test]
#[ignore = "8 layers at T=64: run with --release -- --ignored"]
fn enumerates_every_round_of_the_eight_layer_window() {
    // Worst round LU range_16, 2^-101.9; floor 2^-99.6 (Policy 1) and 2^-99.4
    // (Policy 2, whose 2^-108 column rounds add up), both above 2^-100.
    for (sources, floor) in [(Sources::Expander, 102_066), (Sources::CircleAll, 101_844)] {
        let (_, ledger) = proved("eight-layer", 64, sources);
        let summary = enumerated(&ledger);
        eprintln!("{sources:?}: {summary:?}");
        assert_eq!(summary, (11_687, "LU range_16".to_string(), 104_425, floor));
    }
}

