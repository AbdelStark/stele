/// One honest small window shared by the controls: T = 4, one layer.
fn honest() -> (Case, Statement) {
    let case = load("one-layer");
    let statement = greedy(&mut case.executor(&case.artifact), 4);
    (case, statement)
}

#[test]
fn rejects_statement_and_container_tampers() {
    let (case, statement) = honest();
    let weights = Weights::from_artifact(&case.model, &case.artifact).expect("weights");
    let committed = Committed::new(&weights).expect("commitment");
    let public = case.public(&committed, &weights);
    let mut executor = case.executor(&case.artifact);
    let proof = prove(&public, &mut executor, &weights, &committed, &statement).expect("prove");
    verify(&public, &statement, &proof).expect("honest proof");
    // INV-8: same inputs, same proof bytes.
    let again = prove(&public, &mut executor, &weights, &committed, &statement).expect("prove");
    assert!(proof == again, "deterministic proof bytes");
    // The verifier's input file round-trips exactly.
    let file = bundle::encode(&public, &statement);
    assert_eq!(
        bundle::decode(&file),
        Ok((public.clone(), statement.clone()))
    );

    // Each statement tamper fails fast at the prover-written header digest and, with
    // the header restamped to the verifier's own digest, in the engine: the binding is
    // the transcript (RFC-0026 §4 step 1), not the header.
    let rejects = |p: &Public, s: &Statement| {
        assert_eq!(verify(p, s, &proof).err(), Some(Error::StatementMismatch));
        let mut c = container::decode(&proof).expect("container");
        c.statement = statement_digest_for(p, s).expect("digest");
        let error = verify(p, s, &c.encode()).expect_err("restamped tamper");
        assert!(matches!(error, Error::Engine(_)), "{error:?}");
    };
    // NC-1309: change [r, e).
    let range = Statement {
        start: 1,
        ..statement.clone()
    };
    rejects(&public, &range);
    // A different next token, and a different checked token, under the honest proof.
    let next = Statement {
        next: statement.next.map(|y| y ^ 1),
        ..statement.clone()
    };
    rejects(&public, &next);
    let mut tokens = statement.clone();
    tokens.tokens[2] ^= 1;
    rejects(&public, &tokens);
    // A tampered weight commitment root (a different model commitment).
    let mut other = public.clone();
    other.commitment[0].0[0] ^= 1; // One stacked model source (RFC-0026 A5).
    assert_eq!(other.commitment.len(), 1);
    assert!(verify(&other, &statement, &proof).is_err());
    // A tampered public gain (RFC-0026 A2): absorbed in the first transcript frame.
    let mut gain = public.clone();
    gain.vectors[0].1[0] ^= 1;
    assert_ne!(
        public_input(&gain, &[0; 32], &statement),
        public_input(&public, &[0; 32], &statement)
    );
    rejects(&gain, &statement);
    // The model identity a verifier compares with trusted values moves with a gain or root.
    let identity = model_identity(&public).expect("identity");
    assert_ne!(model_identity(&gain).expect("identity").1, identity.1);
    let mut root = public.clone();
    root.commitment[0].0[0] ^= 1;
    assert_ne!(model_identity(&root).expect("identity").1, identity.1);
    // Not exactly the Model's 1-D records: one dropped, one lengthened.
    let mut short = public.clone();
    short.vectors.pop();
    assert_eq!(
        verify(&short, &statement, &proof).err(),
        Some(Error::StatementMismatch)
    );
    let mut long = public.clone();
    long.vectors[0].1.push(0);
    assert_eq!(
        verify(&long, &statement, &proof).err(),
        Some(Error::StatementMismatch)
    );
    // T beyond the Model's context.
    let wide = Statement {
        tokens: vec![1; 32],
        start: 0,
        end: 32,
        next: Some(1),
    };
    assert_eq!(
        verify(&public, &wide, &proof).err(),
        Some(Error::StatementMismatch)
    );

    // Container shape: truncated, extended, one flipped byte in the body.
    assert_eq!(
        verify(&public, &statement, &proof[..proof.len() - 1]).err(),
        Some(Error::Container(container::Error::ProofShape))
    );
    let mut long = proof.clone();
    long.push(0);
    assert_eq!(
        verify(&public, &statement, &long).err(),
        Some(Error::Container(container::Error::ProofShape))
    );
    // The same bytes with one section boundary moved: the engine derives each length.
    let mut moved = container::decode(&proof).expect("container");
    let byte = moved.multiplicities[0].pop().expect("multiplicity bytes");
    moved.multiplicities[1].insert(0, byte);
    assert_eq!(
        verify(&public, &statement, &moved.encode()).err(),
        Some(Error::Engine(stele_reductions::relation::Error::ProofShape))
    );
    for at in [100, proof.len() / 2, proof.len() - 5] {
        let mut flipped = proof.clone();
        flipped[at] ^= 1;
        assert!(
            verify(&public, &statement, &flipped).is_err(),
            "flip at {at}"
        );
    }
}

/// E16-11: statement tampers against a proof written by `stele prove-dev`, for a real
/// checkpoint (`docs/development-e2e.md`). `STELE_DEV_PROOF` names a directory holding
/// `public.bin` and `proof.bin`. Each tamper fails fast at the header digest and, with
/// the header restamped to the verifier's own digest, in the verifier proper.
#[test]
#[ignore = "needs STELE_DEV_PROOF: run with --release -- --ignored"]
fn rejects_tampers_on_a_supplied_proof() {
    let dir = std::path::PathBuf::from(std::env::var("STELE_DEV_PROOF").expect("STELE_DEV_PROOF"));
    let (public, statement) =
        bundle::decode(&std::fs::read(dir.join("public.bin")).expect("public.bin"))
            .expect("bundle");
    let proof = std::fs::read(dir.join("proof.bin")).expect("proof.bin");
    let clock = Instant::now();
    verify(&public, &statement, &proof).expect("honest proof");
    eprintln!("honest: accepted in {} ms", clock.elapsed().as_millis());
    let rejects = |name: &str, p: &Public, s: &Statement| {
        assert_eq!(verify(p, s, &proof).err(), Some(Error::StatementMismatch));
        let mut c = container::decode(&proof).expect("container");
        c.statement = statement_digest_for(p, s).expect("digest");
        let clock = Instant::now();
        let error = verify(p, s, &c.encode()).expect_err(name);
        eprintln!(
            "{name}: rejected with {error:?} in {} ms",
            clock.elapsed().as_millis()
        );
        error
    };
    // A wrong next token `y`, and a wrong first checked token.
    let next = Statement {
        next: statement.next.map(|y| y ^ 1),
        ..statement.clone()
    };
    assert!(matches!(rejects("next", &public, &next), Error::Engine(_)));
    let mut token = statement.clone();
    token.tokens[statement.start as usize + 1] ^= 1;
    assert!(matches!(
        rejects("token", &public, &token),
        Error::Engine(_)
    ));
    // A tampered model commitment: the first model source's root no longer matches its
    // certificate (RFC-0026 §2.2). The other three tampers change the absorbed public input.
    let mut weight = public.clone();
    weight.commitment[0].0[0] ^= 1;
    assert!(matches!(
        rejects("weight", &weight, &statement),
        Error::Commitment(_)
    ));
    // A tampered public norm gain (RFC-0026 A2).
    let mut gain = public.clone();
    gain.vectors[0].1[0] ^= 1;
    assert!(matches!(
        rejects("gain", &gain, &statement),
        Error::Engine(_)
    ));
}

/// E16-18: time the model commitment alone (RFC-0026 §2.2), which `prove-dev` recomputes
/// on every call. `STELE_DEV_PROOF` names a directory holding `model.bin`, `artifact.bin`
/// and the `public.bin` whose roots the recomputed commitment must equal.
#[test]
#[ignore = "needs STELE_DEV_PROOF: run with --release -- --ignored"]
fn matches_reference_model_commitment_of_a_supplied_proof() {
    let dir = std::path::PathBuf::from(std::env::var("STELE_DEV_PROOF").expect("STELE_DEV_PROOF"));
    let read = |name: &str| std::fs::read(dir.join(name)).expect(name);
    let model = Model::decode(&read("model.bin")).expect("model");
    let artifact = read("artifact.bin");
    let (public, _) = bundle::decode(&read("public.bin")).expect("bundle");
    let clock = Instant::now();
    let weights = Weights::from_artifact(&model, &artifact).expect("weights");
    let committed = Committed::new(&weights).expect("commitment");
    let ns = clock.elapsed().as_nanos();
    assert!(
        committed.commitment == public.commitment,
        "same model commitment"
    );
    eprintln!("model commitment: {ns} ns");
}

/// Research census for formal/zk-claims.md §4.4 (no protocol change): per
/// committed column, the masked claims a dev-zk proof would reveal (one per
/// distinct (zerocheck domain, column, vars map), lookup tuple ref, range, matmul
/// role and compose entry), relation counts, the identity degree, columns too
/// short for their own mask coordinates and relation domains below c_D + 1 = 3
/// variables (QM31). Returns (committed columns, total claims, max claims, short).
fn census(name: &str, t: usize) -> (usize, usize, usize, usize) {
    use std::collections::{BTreeMap, BTreeSet};
    use stele_prover::development::prove_tampered;
    use stele_reductions::stele_ir::relation::{Kind, Ref, Relation};
    let case = load(name);
    let statement = greedy(&mut case.executor(&case.artifact), t);
    let weights = Weights::from_artifact(&case.model, &case.artifact).expect("weights");
    let committed = Committed::new(&weights).expect("commitment");
    let public = case.public(&committed, &weights);
    let mut captured = None;
    let mut hook = |relation: &mut Relation, _: &mut _| captured = Some(relation.clone());
    prove_tampered(
        &public,
        &mut case.executor(&case.artifact),
        &weights,
        &committed,
        &statement,
        &mut hook,
    )
    .expect("prove");
    let relation = captured.expect("relation");
    let committed_column =
        |r: &Ref| !matches!(relation.columns[r.column.0 as usize].kind, Kind::Public(_));
    let mut zero: BTreeSet<(u8, u32, Vec<u8>)> = BTreeSet::new();
    let mut claims: BTreeMap<u32, usize> = BTreeMap::new();
    let mut degree = 0;
    for identity in &relation.identities {
        for term in &identity.terms {
            degree = degree.max(term.factors.len());
            for factor in term.factors.iter().filter(|f| committed_column(f)) {
                zero.insert((identity.vars, factor.column.0, factor.vars.clone()));
            }
        }
    }
    for compose in &relation.composes {
        let log = relation.columns[compose.column.0 as usize].log_len;
        for id in std::iter::once(compose.column).chain(compose.limbs.iter().map(|l| l.0)) {
            zero.insert((log, id.0, (0..log).collect()));
        }
    }
    for (_, column, _) in &zero {
        *claims.entry(*column).or_default() += 1;
    }
    for lookup in &relation.lookups {
        for r in lookup.tuple.iter().filter(|r| committed_column(r)) {
            *claims.entry(r.column.0).or_default() += 1;
        }
    }
    for range in &relation.ranges {
        *claims.entry(range.column.0).or_default() += 1;
    }
    for matmul in &relation.matmuls {
        for r in [&matmul.out, &matmul.lhs, &matmul.rhs] {
            if committed_column(r) {
                *claims.entry(r.column.0).or_default() += 1;
            }
        }
    }
    let committed_columns: Vec<u32> = (0..relation.columns.len() as u32)
        .filter(|&id| !matches!(relation.columns[id as usize].kind, Kind::Public(_)))
        .collect();
    let max = claims.values().copied().max().unwrap_or(0);
    let total: usize = claims.values().sum();
    let mut histogram: BTreeMap<usize, usize> = BTreeMap::new();
    for id in &committed_columns {
        *histogram
            .entry(claims.get(id).copied().unwrap_or(0))
            .or_default() += 1;
    }
    let short = committed_columns
        .iter()
        .filter(|&&id| relation.columns[id as usize].log_len < 3)
        .count();
    let entries: u64 = committed_columns
        .iter()
        .map(|&id| 1u64 << relation.columns[id as usize].log_len)
        .sum();
    let free_out = relation.matmuls.iter().filter(|m| m.summed == 0).count();
    let small_identities = relation.identities.iter().filter(|i| i.vars < 3).count();
    let small_lookups = relation.lookups.iter().filter(|l| l.vars < 3).count();
    let small_ranges = relation
        .ranges
        .iter()
        .filter(|r| relation.columns[r.column.0 as usize].log_len < 3)
        .count();
    let small_matmuls = relation
        .matmuls
        .iter()
        .filter(|m| m.free + m.summed < 3)
        .count();
    // RFC-0026 A3 checks: lookups by table, ranges by width.bits. Per check, the
    // concatenated source length N (each member padded to a power of two, the
    // total rounded up) and the table length |T|, for the GKR cost comparison.
    let mut checks: BTreeMap<(u8, u32), (u64, u64)> = BTreeMap::new();
    for lookup in &relation.lookups {
        let rows = relation.tables[lookup.table.0 as usize].rows.len() as u64;
        let entry = checks.entry((0, lookup.table.0)).or_insert((0, rows));
        entry.0 += 1u64 << lookup.vars;
    }
    for range in &relation.ranges {
        let log = relation.columns[range.column.0 as usize].log_len;
        let bits = u32::from(range.width.bits);
        let entry = checks.entry((1, bits)).or_insert((0, 1u64 << bits));
        entry.0 += 1u64 << log;
    }
    let shape: Vec<(u64, u64)> = checks
        .values()
        .map(|&(n, t)| (n.next_power_of_two(), t.next_power_of_two()))
        .collect();
    eprintln!("census {name} T={t}: checks (N, |T|) = {shape:?}");
    let lookup_entries: u64 = relation.lookups.iter().map(|l| 1u64 << l.vars).sum::<u64>()
        + relation
            .ranges
            .iter()
            .map(|r| 1u64 << relation.columns[r.column.0 as usize].log_len)
            .sum::<u64>();
    eprintln!(
        "census {name} T={t}: {} committed columns ({entries} entries), {total} claims, \
         histogram {histogram:?}, max {max}, identity factors <= {degree}, {} identities, \
         {} lookups, {} ranges ({lookup_entries} looked-up entries), {} matmuls \
         ({free_out} with no summed bit), {} composes, {short} columns with log_len < 3; \
         domains below 3 variables: {small_identities} identities, {small_lookups} \
         lookups, {small_ranges} ranges, {small_matmuls} matmuls",
        committed_columns.len(),
        relation.identities.len(),
        relation.lookups.len(),
        relation.ranges.len(),
        relation.matmuls.len(),
        relation.composes.len(),
    );
    assert!(
        degree <= 3,
        "RFC-0026 §3.2 bounds identity terms at three factors"
    );
    assert_eq!(free_out, 0);
    (committed_columns.len(), total, max, short)
}

