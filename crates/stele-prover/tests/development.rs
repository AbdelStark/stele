//! RFC-0026 E16-10: development end-to-end prove/verify on synthetic family-1 models,
//! and statement/container tampers through the verifier. The RFC-0026 §9 controls
//! NC-1300/1301/1304/1305/1309 run in `tests/negative-controls` (`src/development.rs`).
use std::time::Instant;
use stele_proof::development as container;
use stele_prover::development::{
    bundle, model_identity, prove, public_input, statement_digest_for, verify, Committed, Error,
    Public, Statement, Weights,
};
use stele_reductions::stele_cqis::execution::Executor;
use stele_reductions::stele_cqis::model::{Model, Preparation, Scales};

const RAW: &[u8] = include_bytes!("fixtures/synthetic-e2e.bin");
const JSON: &str = include_str!("fixtures/synthetic-e2e.json");

struct Case {
    model: Model,
    prep: Preparation<'static>,
    scales: Scales,
    bytes: [&'static [u8]; 3],
    artifact: Vec<u8>,
}

fn load(name: &str) -> Case {
    let all: serde_json::Value = serde_json::from_str(JSON).expect("json");
    // The manifest pins the fixture bytes (regenerated by `synthetic_e2e.py`).
    assert_eq!(
        blake3::hash(RAW).to_hex().as_str(),
        all["blake3"].as_str().expect("blake3")
    );
    let c = all["cases"]
        .as_array()
        .expect("cases")
        .iter()
        .find(|c| c["name"] == name)
        .expect("case")
        .clone();
    let span = |key: &str| {
        let o = c[key]["offset"].as_u64().expect("offset") as usize;
        let n = c[key]["length"].as_u64().expect("length") as usize;
        &RAW[o..o + n]
    };
    let artifact = span("artifact").to_vec();
    // The fixture pins each artifact's BLAKE3 digest; the executor checks it on load.
    assert_eq!(
        blake3::hash(&artifact).to_hex().as_str(),
        c["artifact_id"].as_str().expect("artifact id")
    );
    let model = Model::decode(span("model")).expect("model");
    let prep = Preparation::decode(&model, span("preparation")).expect("prep");
    let scales = Scales::decode(&model, span("scales")).expect("scales");
    Case {
        model,
        prep,
        scales,
        bytes: [span("model"), span("scales"), span("preparation")],
        artifact,
    }
}

impl Case {
    fn executor<'a>(&'a self, artifact: &'a [u8]) -> Executor<'a> {
        let id = *blake3::hash(artifact).as_bytes();
        Executor::new(
            &self.model,
            &self.prep,
            &self.scales,
            artifact,
            &id,
            1 << 36,
        )
        .expect("load")
    }

    fn public(&self, committed: &Committed<'_>, weights: &Weights) -> Public {
        Public {
            model: self.bytes[0].to_vec(),
            scales: self.bytes[1].to_vec(),
            preparation: self.bytes[2].to_vec(),
            vectors: weights.vectors.clone(),
            commitment: committed.commitment.clone(),
        }
    }
}

/// Greedy continuation of token 1 to `t` tokens, checked over `[0, t)` with `y`.
fn greedy(executor: &mut Executor<'_>, t: usize) -> Statement {
    let mut tokens = vec![1u32];
    let mut cache = None;
    loop {
        let (step, next) = executor
            .step(*tokens.last().expect("token"), cache.as_ref())
            .expect("step");
        cache = Some(next);
        let logits = step.logits();
        let max = *logits.iter().max().expect("logits");
        let y = logits.iter().position(|v| *v == max).expect("argmax") as u32;
        if tokens.len() == t {
            return Statement {
                tokens,
                start: 0,
                end: t as u32,
                next: Some(y),
            };
        }
        tokens.push(y);
    }
}

/// FNV-1a of proof bytes: any byte change moves it (INV-8).
fn fnv(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325u64, |h, b| {
        (h ^ u64::from(*b)).wrapping_mul(0x0100_0000_01b3)
    })
}

fn run(name: &str, t: usize) -> u64 {
    let case = load(name);
    let mut executor = case.executor(&case.artifact);
    let statement = greedy(&mut executor, t);
    let weights = Weights::from_artifact(&case.model, &case.artifact).expect("weights");
    let clock = Instant::now();
    let committed = Committed::new(&weights).expect("commitment");
    let commit_ms = clock.elapsed().as_millis();
    let public = case.public(&committed, &weights);
    let clock = Instant::now();
    let proof = prove(&public, &mut executor, &weights, &committed, &statement).expect("prove");
    let prove_ms = clock.elapsed().as_millis();
    let sections = container::decode(&proof).expect("container");
    for (label, list) in [
        ("groups", &sections.groups),
        ("multiplicities", &sections.multiplicities),
        ("identities", &sections.identities),
        ("lookups", &sections.lookups),
        ("matmuls", &sections.matmuls),
        ("openings", &sections.openings),
    ] {
        let bytes: usize = list.iter().map(Vec::len).sum();
        eprintln!("{label}: {} sections, {bytes} bytes", list.len());
    }
    let clock = Instant::now();
    let ledger = verify(&public, &statement, &proof).expect("verify");
    let verify_ms = clock.elapsed().as_millis();
    eprintln!(
        "{name}: T={t} proof {} bytes (fnv {:016x}), commit {commit_ms} ms, prove {prove_ms} ms, verify {verify_ms} ms\n{ledger}",
        proof.len(),
        // Identity check across prover-side changes (INV-8): any byte change moves it.
        fnv(&proof)
    );
    fnv(&proof)
}

#[test]
fn accepts_one_layer_window() {
    // Pinned proof bytes: the T=16 window is large enough for the threaded dense
    // rounds (E16-15), and the hash equals the sequential prover's.
    assert_eq!(run("one-layer", 16), 0x035f_65b3_0541_72b5);
}

#[test]
fn accepts_one_layer_grouped_window() {
    assert_eq!(run("one-layer-grouped", 16), 0xeacf_1ac6_dd87_6e3b);
}

