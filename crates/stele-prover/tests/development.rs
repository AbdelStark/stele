/// RFC-0013 A5, RFC-0026 A9 (E12-14b): one window proven under dev-zk through the
/// development orchestrator and verified by the dev-zk verifier; the profile byte
/// is bound by the transcript (a development-profile transcript rejects).
fn zk_window(name: &str, t: usize, profile: u8) -> (u64, u64) {
    let (hash, _, interactive) = zk_window_sources(name, t, profile);
    (hash, interactive)
}

/// [`zk_window`] and each source's `(ell, policy)` from the proof's source bytes, in
/// proof order: claim sources, then the shared source (RFC-0013 A8 item 2), and the
/// ledger's `ε_interactive·|K|` (E12-26).
fn zk_window_sources(name: &str, t: usize, profile: u8) -> (u64, Vec<(u32, Policy)>, u64) {
    use stele_prover::development::zk;
    let case = load(name);
    let statement = greedy(&mut case.executor(&case.artifact), t);
    let weights = Weights::from_artifact(&case.model, &case.artifact).expect("weights");
    let base = Public {
        model: case.bytes[0].to_vec(),
        scales: case.bytes[1].to_vec(),
        preparation: case.bytes[2].to_vec(),
        vectors: zk::published(case.bytes[0], &weights.vectors).expect("published"),
        commitment: Vec::new(),
        sources: Sources::Expander,
    };
    // RFC-0013 A6: commit once (budget 2), then prove as index 0.
    let (commitment, mut state) = zk::commit(
        &base,
        &mut case.executor(&case.artifact),
        &weights,
        t,
        2,
        [7; 32],
        profile,
    )
    .expect("commit");
    let public = Public {
        commitment: vec![(commitment.root, Vec::new())],
        ..base.clone()
    };
    let index = state.take(&commitment).expect("index");
    let start = Instant::now();
    let (proof, revealed) = zk::prove(
        &public,
        &mut case.executor(&case.artifact),
        &weights,
        &statement,
        zk::Seed::new([42; 32]),
        &commitment,
        &state,
        index,
    )
    .expect("dev-zk prove");
    state.revealed.push(revealed);
    let proved = start.elapsed();
    let start = Instant::now();
    let verified =
        zk::verify(&public, &statement, &proof, &commitment, index).expect("dev-zk verify");
    eprintln!(
        "dev-zk {name} T={t}: prove {proved:?}, verify {:?}, {verified}",
        start.elapsed()
    );
    // The public bundle round-trips with its profile, commitment and index; the
    // model state too.
    let bytes = bundle::encode_zk(&public, &statement, &commitment, index);
    assert_eq!(
        bundle::decode_profile(&bytes).expect("bundle"),
        (public.clone(), statement.clone(), profile)
    );
    assert_eq!(
        bundle::decode_zk(&bytes).expect("bundle"),
        (public.clone(), statement.clone(), commitment.clone(), index)
    );
    assert!(
        bundle::decode(&bytes).is_err(),
        "a dev-zk bundle is not development"
    );
    assert_eq!(
        zk::ModelState::decode(&state.encode()).expect("state"),
        state
    );
    assert_eq!(
        zk::ModelCommitment::decode(&commitment.encode()).expect("commitment"),
        commitment
    );
    // RFC-0013 A6 item 5 (review F4): a failed proof spends no index. The state is
    // persisted with the index taken, then restored and persisted again.
    let prior = state.clone();
    let mut saved: Vec<zk::ModelState> = Vec::new();
    let mut bad = statement.clone();
    bad.next = bad.next.map(|y| y ^ 1);
    let failed = zk::prove_next(
        &public,
        &mut case.executor(&case.artifact),
        &weights,
        &bad,
        zk::Seed::new([43; 32]),
        &commitment,
        &mut state,
        &mut |s: &zk::ModelState| {
            saved.push(s.clone());
            Ok(())
        },
    );
    assert!(failed.is_err());
    assert_eq!(state, prior, "the state is restored");
    assert_eq!(saved.len(), 2);
    assert_eq!(
        saved[0].next,
        prior.next + 1,
        "the index is persisted before proving"
    );
    assert_eq!(saved[1], prior, "and restored after the failure");
    // RFC-0013 A6 (review F1): a wrong secret (another model seed) rebuilds other
    // masks; the producer refuses before any transcript work.
    let wrong = zk::ModelState {
        profile,
        seed: [8; 32],
        next: state.next + 1,
        revealed: state.revealed.clone(),
    };
    let refused = zk::prove(
        &public,
        &mut case.executor(&case.artifact),
        &weights,
        &statement,
        zk::Seed::new([44; 32]),
        &commitment,
        &wrong,
        state.next,
    );
    assert_eq!(
        refused.err(),
        Some(Error::Zk(stele_reductions::zk::Error::Pcs(
            stele_reductions::stele_pcs::Error::Merkle(
                stele_reductions::stele_hash::merkle::Error::RootMismatch
            )
        )))
    );
    // Another index of the same commitment is rejected.
    assert!(zk::verify(&public, &statement, &proof, &commitment, 1).is_err());
    // A different window under the same public data is rejected.
    let mut other = statement.clone();
    other.next = other.next.map(|y| y ^ 1);
    assert!(zk::verify(&public, &other, &proof, &commitment, index).is_err());
    // RFC-0026 A11, A12: a dev-zk input naming a Circle source set is rejected.
    for sources in [Sources::Circle, Sources::CircleAll] {
        let circle = Public {
            sources,
            ..public.clone()
        };
        assert_eq!(
            zk::verify(&circle, &statement, &proof, &commitment, index).err(),
            Some(Error::StatementMismatch)
        );
    }
    // Every seed above is fixed, so the proof is too: identity check across
    // prover-side changes (INV-8, E16-24).
    // RFC-0013 A8 item 1: a state of the other byte never proves against this
    // commitment; nothing is taken or persisted.
    let mut other = zk::ModelState {
        profile: if profile == zk::PROFILE {
            zk::PROFILE_BALANCED
        } else {
            zk::PROFILE
        },
        ..state.clone()
    };
    assert_eq!(other.take(&commitment), Err(Error::StatementMismatch));
    assert_eq!(
        zk::prove(
            &public,
            &mut case.executor(&case.artifact),
            &weights,
            &statement,
            zk::Seed::new([45; 32]),
            &commitment,
            &other,
            state.next,
        )
        .err(),
        Some(Error::StatementMismatch)
    );
    let decoded =
        stele_reductions::zk::claims::decode::<QM31>(&proof[b"stele-dev-zk-v1".len() + 64..])
            .expect("claims proof");
    let sources: Vec<(u32, Policy)> = decoded
        .sources
        .iter()
        .map(|bytes| {
            let source = Source::<QM31>::from_bytes(bytes).expect("source");
            (
                source.rows().trailing_zeros() - 1,
                source.parameters().policy,
            )
        })
        .collect();
    eprintln!(
        "dev-zk {name} byte {profile}: proof fnv {:016x}, {} bytes, sources (ell, policy) {sources:?}",
        fnv(&proof),
        proof.len()
    );
    check_ledger(&verified, sources.len(), profile);
    (fnv(&proof), sources, verified.ledger.interactive())
}

/// E12-26: the verifier's dev-zk ledger has one SC and one MASK line per masked
/// instance, LU and ZD per check, and PCS rounds for every hiding source (the
/// claim sources, the shared source and the shared batch's A4 source). Under byte
/// 4 every PCS round is at most `2^-108` (A14 item 5), so the worst round is an
/// ungrinded algebraic round; it is printed for both bytes.
fn check_ledger(verified: &stele_prover::development::zk::Verified, sources: usize, profile: u8) {
    use stele_prover::development::zk;
    let ledger = &verified.ledger;
    let count = |line: Line| ledger.entries.iter().filter(|e| e.line == line).count();
    let instances = verified.relations + verified.gkr + verified.batches;
    assert_eq!(count(Line::Mask), instances);
    assert_eq!(count(Line::Sc), instances);
    assert!(count(Line::Lu) > 0);
    assert_eq!(count(Line::Lu), count(Line::Zd));
    assert_eq!(ledger.pcs.len(), sources + 1);
    assert_eq!(
        ledger.interactive(),
        ledger.entries.iter().map(|e| e.numerator).sum::<u64>()
    );
    let worst = ledger.worst().expect("rounds");
    let pcs = ledger
        .rounds()
        .into_iter()
        .filter(|r| r.line.starts_with("PCS"))
        .map(|r| r.bits)
        .min()
        .expect("PCS rounds");
    if profile == zk::PROFILE_BALANCED {
        assert!(
            pcs >= 108 * 1024,
            "every byte-4 PCS round is at most 2^-108"
        );
        assert!(ledger
            .pcs
            .iter()
            .all(|s| s.parameters.policy == Policy::Two));
        assert_eq!(worst.grind, 0, "the worst byte-4 round is ungrinded");
        assert_eq!(worst.line, "LU+ZD", "and it is a check's (β, α) round");
    } else {
        // Byte 1 (Policy 1): the witness source's ungrinded tensor round
        // `2·ell·(e + 1)/|K|` is worse than any LU round on both synthetic windows.
        assert_eq!(
            (worst.line, worst.name.as_str()),
            ("PCS tensor", "source 0")
        );
    }
    let text = verified.to_string();
    assert!(text.contains("worst round\t") && text.ends_with("FS unproven, PCS conjectural"));
    eprintln!(
        "dev-zk byte {profile} ledger: eps_interactive <= {}/p^4, worst round {} {} {}, best PCS {}",
        ledger.interactive(),
        worst.line,
        worst.name,
        stele_reductions::zk::claims::tenths(worst.bits),
        stele_reductions::zk::claims::tenths(pcs),
    );
}

